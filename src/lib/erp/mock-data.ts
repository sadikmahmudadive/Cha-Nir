export function generateSeedInventory(): InventoryItem[] {
  const items: InventoryItem[] = [];
  PRODUCTS.forEach((product) => {
    product.variants.forEach((variant) => {
      const isHeavy = variant.grams >= 5000;
      const initialUnits = isHeavy
        ? Math.floor(15 + Math.random() * 25)
        : Math.floor(60 + Math.random() * 120);

      const reorder = isHeavy ? 10 : 30;

      items.push({
        id: `SKU-${product.slug}-${variant.id}`,
        productSlug: product.slug,
        productName: product.name,
        variantId: variant.id,
        variantLabel: variant.label,
        category: product.category,
        grade: product.grade,
        grams: variant.grams,
        inStockUnits: initialUnits,
        inStockKg: Math.round((initialUnits * variant.grams) / 1000),
        reorderPointUnits: reorder,
        unitCost: Math.round(variant.price * 0.62), // ~38% gross margin
        unitPrice: variant.price,
        batchId: `BATCH-2026-${product.grade.replace(/[^A-Za-z]/g, "").toUpperCase().slice(0, 3)}-02`,
        lastRestocked: "2026-10-28",
      });
    });
  });
  return items;
}

